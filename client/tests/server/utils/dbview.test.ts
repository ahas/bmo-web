import { describe, expect, test } from "bun:test";

import { SQL } from "bun";

import { connectionOf } from "../../../apps/web/server/utils/db";
import { DB_MASKED_TEXT } from "../../../apps/web/shared/config";
import { wording } from "../../../apps/web/shared/wording";
import { scratchWebDatabase } from "../../support/web-database";

// Reading the console's own database as tables of rows, on a scratch database of the server's shape with tables of
// the test's own beside the console's. The two things worth pinning here are the two the screen rests on and
// neither of which a person can see by looking: that nothing on this road can write, and that a read the screen
// stops stops on the database at once.

const address = await scratchWebDatabase();
const made = new SQL(connectionOf(address) as SQL.Options);

await made.unsafe(`
  CREATE TABLE notes (id bigint PRIMARY KEY, title text NOT NULL, body text, data bytea, rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE);
  CREATE TABLE wide (a bigint);
`).simple();

for (let at = 1; at <= 10; at++) {
  await made.unsafe("INSERT INTO notes (id, title, body) VALUES ($1, $2, $3)", [at, `Title ${at}`, at === 1 ? "x".repeat(900) : null]);
}

await made.unsafe("INSERT INTO notes (id, title, data) VALUES (11, 'bytes', '\\x01020304'::bytea)");
await made.unsafe("INSERT INTO web_users (name, password_hash, created_at) VALUES ('member-a', 'sha-secret', 1)");
await made.unsafe("INSERT INTO wide (a) SELECT generate_series(1, 600)");
await made.close();

const {
  askDatabase,
  asRows,
  browseStatements,
  countsSql,
  DbStoppedError,
  DbViewError,
  likeTerm,
  listDbTables,
  maskResult,
  openDbRead,
  quoted,
  readDbSchema,
  stopDbRead,
  wrapQuery
} = await import("../../../apps/web/server/utils/dbview");

describe("what the database is read as", () => {
  test("a row cannot be changed, because the database itself refuses it", async () => {
    await expect(askDatabase([{ sql: "UPDATE notes SET title = 'x'", params: [] }])).rejects.toThrow(/read-only/i);
  });

  test("nor can a table be made, dropped or emptied", async () => {
    for (const sql of ["CREATE TABLE gone (a int)", "DROP TABLE notes", "DELETE FROM notes"]) {
      await expect(askDatabase([{ sql, params: [] }])).rejects.toThrow(/read-only/i);
    }
  });

  test("a refusal is the database's own word rather than this app's failure", async () => {
    await expect(askDatabase([{ sql: "SELECT * FROM nowhere", params: [] }])).rejects.toBeInstanceOf(DbViewError);
  });

  test("reading is what it is for", async () => {
    const [answered] = await askDatabase([{ sql: "SELECT count(*) FROM notes", params: [] }]);

    expect(answered?.rows[0]?.[0]?.text).toBe("11");
  });
});

describe("a query that would never end", () => {
  test("waits for its answer until the screen stops it, and then stops on the database at once", async () => {
    const key = "read-a-0000000000000001";
    const read = openDbRead(key);
    const forever = askDatabase([{ sql: "SELECT count(*) FROM wide a, wide b, wide c, wide d", params: [] }], { read });
    const settled = forever.then(
      () => "answered",
      (error: unknown) => error
    );

    // Running on the database before it is stopped; nothing but the stop ends it.
    for (let looked = 0; looked < 100 && !(await running()); looked++) await Bun.sleep(50);
    expect(await running()).toBe(true);

    const stoppedAt = Date.now();

    stopDbRead(key);

    expect(await settled).toBeInstanceOf(DbStoppedError);
    expect(Date.now() - stoppedAt).toBeLessThan(4_000);
    expect(await running()).toBe(false);
  });

  test("is not run at all where its stop reached the screen's key first", async () => {
    const key = "read-a-0000000000000002";

    stopDbRead(key);

    await expect(askDatabase([{ sql: "SELECT 1", params: [] }], { read: openDbRead(key) })).rejects.toBeInstanceOf(DbStoppedError);
  });
});

// Whether the endless query runs on the database now, asked on a connection of its own.
async function running(): Promise<boolean> {
  const looking = new SQL(connectionOf(address) as SQL.Options);

  try {
    const [row] = await looking.unsafe(
      "SELECT count(*)::int AS n FROM pg_stat_activity WHERE state = 'active' AND pid <> pg_backend_pid() AND query LIKE '%wide a, wide b, wide c, wide d%'"
    );

    return (row as { n: number }).n > 0;
  } finally {
    await looking.close();
  }
}

describe("what a statement is allowed to answer with", () => {
  test("stops at the row cap and says that is where it stopped", async () => {
    const [answered] = await askDatabase([{ sql: "SELECT id FROM notes ORDER BY id", params: [] }], { rowCap: 3 });

    expect(answered?.rows.length).toBe(3);
    expect(answered?.cut).toBe(true);
  });

  test("an answer that fits is not marked as cut", async () => {
    const [answered] = await askDatabase([{ sql: "SELECT id FROM notes ORDER BY id LIMIT 2", params: [] }], { rowCap: 3 });

    expect(answered?.cut).toBe(false);
  });

  test("a long value arrives cut, with the whole length said", async () => {
    const [answered] = await askDatabase([{ sql: "SELECT body FROM notes WHERE id = 1", params: [] }], { cellCap: 20 });
    const cell = answered?.rows[0]?.[0];

    expect(cell?.text.length).toBe(20);
    expect(cell?.cut).toBe(true);
    expect(cell?.length).toBe(900);
  });

  test("NULL is nothing rather than an empty value", async () => {
    const [answered] = await askDatabase([{ sql: "SELECT body FROM notes WHERE id = 2", params: [] }]);

    expect(answered?.rows[0]?.[0]).toBeNull();
  });

  test("a JSON value goes with its shape, and whole where it is read whole", async () => {
    const [answered] = await askDatabase([
      { sql: `SELECT '{"role":"worker","tags":["a"]}'::jsonb AS one, '[1,2,3]'::text AS two, 'plain'::text AS three`, params: [] }
    ]);
    const [one, two, three] = answered?.rows[0] ?? [];

    expect(one).toMatchObject({ shape: "object", count: 2, keys: ["role", "tags"], json: { role: "worker", tags: ["a"] }, cut: false });
    expect(two).toMatchObject({ shape: "list", count: 3, json: [1, 2, 3] });
    expect(three?.shape).toBeUndefined();
  });

  test("bytes are said to be bytes rather than shown as letters", async () => {
    const [answered] = await askDatabase([{ sql: "SELECT data FROM notes WHERE title = 'bytes'", params: [] }]);

    expect(answered?.rows[0]?.[0]?.text).toBe("<4 bytes>");
  });

  test("a value travels as an argument, so a quote in it is a quote", async () => {
    const [answered] = await askDatabase([{ sql: "SELECT count(*) FROM notes WHERE title = $1", params: ["'; --"] }]);

    expect(answered?.rows[0]?.[0]?.text).toBe("0");
  });
});

describe("a statement the owner typed", () => {
  test("is made into a subquery, so anything but a SELECT will not parse", async () => {
    for (const sql of ["UPDATE notes SET title = 'x'", "DROP TABLE notes", "SET search_path = nowhere"]) {
      await expect(askDatabase([{ sql: wrapQuery(sql, 10), params: [] }])).rejects.toThrow(/syntax error/i);
    }
  });

  test("nor will two statements at once, however the second one is hidden", async () => {
    await expect(askDatabase([{ sql: wrapQuery("SELECT 1; DROP TABLE notes", 10), params: [] }])).rejects.toThrow(/syntax error/i);
  });

  test("a SELECT of its own is run as it stands, a CTE among them", async () => {
    const [answered] = await askDatabase([{ sql: wrapQuery("WITH one AS (SELECT 1 AS a) SELECT a FROM one", 10), params: [] }]);

    expect(answered?.rows[0]?.[0]?.text).toBe("1");
  });

  test("a trailing semicolon is a person's habit rather than a second statement", async () => {
    const [answered] = await askDatabase([{ sql: wrapQuery("SELECT 2 AS a;  ", 10), params: [] }]);

    expect(answered?.rows[0]?.[0]?.text).toBe("2");
  });
});

describe("what the database is made of", () => {
  test("every table, with how many rows each holds, and whether it keeps a row number", async () => {
    const tables = await listDbTables();

    expect(tables.map((table) => table.name)).toContain("notes");
    expect(tables.map((table) => table.name)).toContain("web_users");
    expect(tables.find((table) => table.name === "notes")).toEqual({ name: "notes", rows: 11, hasRowid: true });
    expect(tables.find((table) => table.name === "wide")).toEqual({ name: "wide", rows: 600, hasRowid: false });
  });

  test("one table's columns, as the database describes them, without the row number", async () => {
    const schema = await readDbSchema("notes");

    expect(schema.columns.map((column) => column.name)).toEqual(["id", "title", "body", "data"]);
    expect(schema.columns[0]?.primaryKey).toBe(true);
    expect(schema.columns[1]?.required).toBe(true);
    expect(schema.ddl).toContain("CREATE TABLE notes");
    expect(schema.hasRowid).toBe(true);
  });

  test("a name that is no table describes nothing, which is how it is known", async () => {
    expect((await readDbSchema("nowhere")).columns.length).toBe(0);
  });
});

describe("the columns this console withholds", () => {
  test("are marked as withheld where the table is described", async () => {
    const schema = await readDbSchema("web_users");

    expect(schema.columns.find((column) => column.name === "password_hash")?.masked).toBe(true);
    expect(schema.columns.find((column) => column.name === "name")?.masked).toBe(false);
  });

  test("never leave the database at all, since the value is not what is selected", async () => {
    const schema = await readDbSchema("web_users");
    const statements = browseStatements({ table: "web_users", columns: schema.columns, hasRowid: true, query: null, sort: null, descending: false, limit: 10, offset: 0 });
    const [read] = await askDatabase([statements.rows]);
    const row = asRows(read as never, true)[0];
    const at = (name: string) => schema.columns.findIndex((column) => column.name === name);

    expect(row?.cells[at("name")]?.text).toBe("member-a");
    expect(row?.cells[at("password_hash")]?.text).toBe(wording(DB_MASKED_TEXT));
  });

  test("are not searched either: a row found or not found is an answer about the value", async () => {
    const schema = await readDbSchema("web_users");
    const statements = browseStatements({ table: "web_users", columns: schema.columns, hasRowid: true, query: "sha-secret", sort: null, descending: false, limit: 10, offset: 0 });
    const [counted] = await askDatabase([statements.count]);

    expect(counted?.rows[0]?.[0]?.text).toBe("0");
  });

  test("are blanked out of a typed query's answer by the name the query gave them", () => {
    const rows = [{ rowid: null, cells: [{ text: "member-a", cut: false, length: 8 }, { text: "sha-secret", cut: false, length: 10 }] }];
    const masked = maskResult(["name", "password_hash"], rows);

    expect(masked.masked).toEqual([false, true]);
    expect(masked.rows[0]?.cells[1]?.text).toBe(wording(DB_MASKED_TEXT));
    expect(masked.rows[0]?.cells[0]?.text).toBe("member-a");
  });
});

describe("one page of a table", () => {
  const columns = [
    { name: "id", type: "bigint", required: true, primaryKey: true, masked: false },
    { name: "title", type: "text", required: true, primaryKey: false, masked: false }
  ];

  function ask(over: Partial<Parameters<typeof browseStatements>[0]> = {}) {
    return browseStatements({ table: "notes", columns, hasRowid: true, query: null, sort: null, descending: false, limit: 50, offset: 0, ...over });
  }

  test("stands in the table's own order, newest first, until a column is picked", () => {
    expect(ask().rows.sql).toContain("ORDER BY rowid DESC");
    expect(ask({ sort: "title", descending: true }).rows.sql).toContain(`ORDER BY "title" DESC`);
  });

  test("a column that is not the table's is no order at all", () => {
    expect(ask({ sort: "nowhere" }).rows.sql).toContain("ORDER BY rowid DESC");
  });

  test("carries the number the table knows each row by, which is how the whole row is asked for", () => {
    expect(ask().rows.sql).toContain("SELECT rowid, ");
    expect(ask({ hasRowid: false }).rows.sql).not.toContain("rowid");
  });

  test("counts the same rows the page is a page of", () => {
    const both = ask({ query: "alpha" });

    expect(both.count.params).toEqual(both.rows.params);
    expect(both.count.sql).toContain("count(*)");
  });

  test("a search reads every column of the table rather than the page in hand", async () => {
    const [counted] = await askDatabase([ask({ query: "title 1" }).count]);

    // Title 1 and Title 10 — both of them, whatever their case, and neither of them on the first page of a search.
    expect(counted?.rows[0]?.[0]?.text).toBe("2");
  });

  test("the page asked for is the page answered with", async () => {
    const [read] = await askDatabase([ask({ limit: 2, offset: 4, sort: "id", descending: false }).rows]);

    expect(asRows(read as never, true).map((row) => row.cells[0]?.text)).toEqual(["5", "6"]);
  });
});

describe("names and terms as SQL carries them", () => {
  test("a name is quoted, and a quote inside it is doubled rather than escaping the quoting", () => {
    expect(quoted("notes")).toBe(`"notes"`);
    expect(quoted(`a"b`)).toBe(`"a""b"`);
  });

  test("what LIKE reads as an instruction is escaped, so a search finds what was typed", () => {
    expect(likeTerm("50%")).toBe("%50\\%%");
    expect(likeTerm("a_b")).toBe("%a\\_b%");
    expect(likeTerm("c\\d")).toBe("%c\\\\d%");
  });

  test("counting every table at once names each of them once", () => {
    expect(countsSql(["notes", "wide"])).toBe(`SELECT 'notes' AS name, count(*) AS rows FROM "notes" UNION ALL SELECT 'wide' AS name, count(*) AS rows FROM "wide"`);
  });
});
