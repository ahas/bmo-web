-- The room relations made again, holding nothing (docs/accounts.md, 「The tables」): the table of a grant's words,
-- empty and shaped as the baseline makes it, and the room kind's fifteen relations in the rules' projection. The
-- service's start writes the rest of the projection from the rules it runs.

CREATE TABLE public.grant_words (
    resource_type text NOT NULL,
    resource_id text NOT NULL,
    relation text NOT NULL,
    subject_key text NOT NULL,
    words text NOT NULL,
    message_chat bigint,
    message_id bigint,
    written_at bigint NOT NULL,
    rowid bigint NOT NULL
);

ALTER TABLE public.grant_words ALTER COLUMN rowid ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.grant_words_rowid_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.grant_words
    ADD CONSTRAINT grant_words_pkey PRIMARY KEY (resource_type, resource_id, relation, subject_key);

ALTER TABLE ONLY public.grant_words
    ADD CONSTRAINT grant_words_rowid_key UNIQUE (rowid);

