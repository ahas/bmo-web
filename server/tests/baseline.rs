//! The schema's starting point (docs/accounts.md, 「The tables」): a blank database gets the baseline whole, with the
//! rows it starts with; an install holding the record of the last release before 1.0.0, or the baseline beside the
//! migrations it has taken in, is taken as it stands, with what the baseline no longer makes taken away; one holding
//! part of the last release's record is refused; and the baseline's way down leaves the database blank.

use std::sync::Arc;

use crate::support::{Blank, Rooms, names, ready};

use bmo_web_server::migration::{BASELINE, BEFORE, FOLDED, MIGRATIONS_TABLE, Migrator, up};
use bmo_web_server::routes::stand;
use sea_orm::{ConnectionTrait, DatabaseConnection, DbBackend, Statement};
use sea_orm_migration::MigratorTrait;

const SCHEMA: &str = include_str!("../src/migration/baseline.sql");

/// A row of the service's own, which an install taken as it stands keeps.
const ROW: &str =
  r#"INSERT INTO "web_users" ("name", "password_hash", "created_at") VALUES ('agent-a', 'hash', 1)"#;

// Every column, index, constraint, function and trigger of the store but the record's, in one line.
fn shape_sql() -> String {
  format!(
    "SELECT COALESCE((SELECT string_agg(table_name || '.' || column_name || ' ' || data_type || ' ' || \
     is_nullable || ' ' || COALESCE(column_default, ''), ', ' ORDER BY table_name, ordinal_position) \
     FROM information_schema.columns WHERE table_schema = current_schema() AND table_name <> '{MIGRATIONS_TABLE}'), '') \
     || ' / ' || COALESCE((SELECT string_agg(indexdef, ', ' ORDER BY indexname) FROM pg_indexes \
     WHERE schemaname = current_schema() AND tablename <> '{MIGRATIONS_TABLE}'), '') \
     || ' / ' || COALESCE((SELECT string_agg(c.conrelid::regclass::text || ' ' || c.conname || ' ' || \
     pg_get_constraintdef(c.oid), ', ' ORDER BY c.conrelid::regclass::text, c.conname) FROM pg_constraint c \
     WHERE c.connamespace = current_schema()::regnamespace AND c.conrelid <> '{MIGRATIONS_TABLE}'::regclass), '') \
     || ' / ' || COALESCE((SELECT string_agg(p.proname, ', ' ORDER BY p.proname) FROM pg_proc p \
     WHERE p.pronamespace = current_schema()::regnamespace), '') \
     || ' / ' || COALESCE((SELECT string_agg(t.tgrelid::regclass::text || ' ' || t.tgname, ', ' \
     ORDER BY t.tgrelid::regclass::text, t.tgname) FROM pg_trigger t WHERE NOT t.tgisinternal), '') AS shape"
  )
}

async fn texts(db: &DatabaseConnection, sql: &str) -> Vec<String> {
  db.query_all(Statement::from_string(DbBackend::Postgres, sql.to_owned()))
    .await
    .unwrap()
    .iter()
    .map(|row| row.try_get_by_index::<String>(0).unwrap())
    .collect()
}

async fn shape(db: &DatabaseConnection) -> Vec<String> {
  texts(db, &shape_sql()).await
}

async fn recorded(db: &DatabaseConnection) -> Vec<String> {
  texts(db, &format!(r#"SELECT "version" FROM "{MIGRATIONS_TABLE}" ORDER BY "version""#)).await
}

// The baseline laid by hand, with the record table beside it.
async fn laid(db: &DatabaseConnection) {
  db.execute_unprepared(SCHEMA).await.unwrap();
  record_table(db).await;
}

// The record table, as the migrator makes it, standing where a laid schema has none.
async fn record_table(db: &DatabaseConnection) {
  db.execute_unprepared(&format!(
    r#"CREATE TABLE IF NOT EXISTS "{MIGRATIONS_TABLE}" ("version" varchar PRIMARY KEY, "applied_at" bigint NOT NULL)"#
  ))
  .await
  .unwrap();
}

// What an install made before the baseline took the room relations and the agent object kinds away may still
// hold: the table of a grant's words with a row, those kinds' projection and a grant on each, beside a section's
// projection and grant, which stay.
const UNMADE: &str = r#"
  CREATE TABLE "grant_words" (
    "resource_type" text NOT NULL, "resource_id" text NOT NULL, "relation" text NOT NULL,
    "subject_key" text NOT NULL, "words" text NOT NULL, "message_chat" bigint, "message_id" bigint,
    "written_at" bigint NOT NULL, "rowid" bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    PRIMARY KEY ("resource_type", "resource_id", "relation", "subject_key"));
  INSERT INTO "grant_words" ("resource_type", "resource_id", "relation", "subject_key", "words", "written_at")
    VALUES ('bmo_room', '-100', 'rule', 'user:2', 'may have their own items approved', 1);
  INSERT INTO "relation_definitions" ("resource_type", "relation", "kind", "subject_types") VALUES
    ('bmo_room', 'ask', 'stored', '{user,bmo_member}'), ('bmo_room', 'rule', 'stored', '{user}'),
    ('bmo_worker', 'run', 'stored', '{user}'), ('bmo_repository', 'change', 'stored', '{user}'),
    ('bmo_tools', 'use', 'stored', '{user}'), ('bmo_section', 'read', 'stored', '{user}');
  INSERT INTO "permission_definitions" ("resource_type", "permission", "rewrite") VALUES
    ('bmo_room', 'may_ask', '{}'), ('bmo_worker', 'may_run', '{}'), ('bmo_section', 'may_read', '{}');
  INSERT INTO "relation_tuples"
    ("resource_type", "resource_id", "relation", "subject_type", "subject_id", "subject_relation") VALUES
    ('bmo_room', '-100', 'ask', 'user', '1', ''), ('bmo_room', '-100', 'ask', 'bmo_member', '-100', ''),
    ('bmo_room', '-100', 'rule', 'user', '2', ''), ('bmo_worker', 'worker-a', 'run', 'user', '1', ''),
    ('bmo_repository', 'repo-a', 'change', 'user', '1', ''), ('bmo_tools', 'room.tools', 'use', 'user', '1', ''),
    ('bmo_section', 'notes', 'read', 'user', '1', '');
"#;

// The kinds the rules no longer declare.
const GONE: &str = "('bmo_room', 'bmo_member', 'bmo_worker', 'bmo_repository', 'bmo_tools')";

// A blank database holding the baseline's schema, what it no longer makes and a row, recorded with `versions`.
async fn installed_with(blank: &Blank, versions: &[&str]) {
  laid(&blank.db).await;
  blank.db.execute_unprepared(UNMADE).await.unwrap();
  for version in versions {
    blank
      .db
      .execute_unprepared(&format!(
        r#"INSERT INTO "{MIGRATIONS_TABLE}" ("version", "applied_at") VALUES ('{version}', 1)"#
      ))
      .await
      .unwrap();
  }
  blank.db.execute_unprepared(ROW).await.unwrap();
}

// An install from before 1.0.0 that ran the first `through` migrations of its last release.
async fn installed(blank: &Blank, through: usize) {
  installed_with(blank, &BEFORE[..through]).await;
}

// One count a statement answers, as text.
async fn count(db: &DatabaseConnection, sql: &str) -> String {
  texts(db, &format!("SELECT ({sql})::text")).await.remove(0)
}

// What an install taken as it stands keeps and loses: its own row and the section's grant stay; every tuple, every
// projection row of the kinds gone and the words' table go.
async fn kept_its_own_and_lost_the_unmade(db: &DatabaseConnection) {
  assert_eq!(count(db, r#"SELECT COUNT(*) FROM "web_users""#).await, "1");
  assert_eq!(
    count(
      db,
      &format!(r#"SELECT COUNT(*) FROM "relation_tuples" WHERE "resource_type" IN {GONE}"#)
    )
    .await,
    "0"
  );
  assert_eq!(
    count(db, r#"SELECT COUNT(*) FROM "relation_tuples" WHERE "subject_type" = 'bmo_member'"#).await,
    "0"
  );
  assert_eq!(
    count(db, r#"SELECT COUNT(*) FROM "relation_tuples" WHERE "resource_type" = 'bmo_section'"#).await,
    "1"
  );
  for projection in ["relation_definitions", "permission_definitions"] {
    assert_eq!(
      count(db, &format!(r#"SELECT COUNT(*) FROM "{projection}" WHERE "resource_type" IN {GONE}"#)).await,
      "0",
      "{projection}"
    );
    assert_eq!(
      count(
        db,
        &format!(r#"SELECT COUNT(*) FROM "{projection}" WHERE "resource_type" = 'bmo_section'"#)
      )
      .await,
      "1",
      "{projection}"
    );
  }
  assert_eq!(count(db, "SELECT COUNT(*) FROM pg_tables WHERE tablename = 'grant_words'").await, "0");
}

#[tokio::test]
async fn a_blank_database_gets_the_baseline_whole_with_the_rows_it_starts_with() {
  let migrated = Blank::new().await;
  let by_hand = Blank::new().await;

  up(&migrated.db).await.unwrap();
  laid(&by_hand.db).await;

  assert_eq!(shape(&migrated.db).await, shape(&by_hand.db).await);
  assert_eq!(recorded(&migrated.db).await, [BASELINE]);
  assert_eq!(
    count(&migrated.db, "SELECT COUNT(*) FROM pg_tables WHERE tablename = 'grant_words'").await,
    "0"
  );

  let counted = |table: &str| format!(r#"SELECT COUNT(*)::text FROM "{table}""#);

  for (table, rows) in [
    ("relation_definitions", "5"),
    ("mail_forms", "4"),
    ("supply_settings", "1"),
    ("chain_links", "1"),
  ] {
    assert_eq!(texts(&migrated.db, &counted(table)).await, [rows], "{table}");
  }
  assert_eq!(
    texts(&migrated.db, r#"SELECT "key" FROM "secret_kinds" ORDER BY "position""#).await,
    [
      "api-key",
      "account-login",
      "aws-access-key",
      "oauth-client",
      "database",
      "ssh-private-key",
      "file",
      "card",
      "delivery-address"
    ]
  );
}

#[tokio::test]
async fn an_install_at_the_last_release_before_the_baseline_is_taken_as_the_baseline() {
  ready();
  let blank = Blank::new().await;
  let migrated = Blank::new().await;

  installed(&blank, BEFORE.len()).await;
  up(&migrated.db).await.unwrap();

  let before = shape(&migrated.db).await;

  up(&blank.db).await.unwrap();
  assert_eq!(recorded(&blank.db).await, [BASELINE]);
  assert_eq!(shape(&blank.db).await, before);
  assert_eq!(texts(&blank.db, r#"SELECT COUNT(*)::text FROM "secret_kinds""#).await, ["0"]);
  kept_its_own_and_lost_the_unmade(&blank.db).await;

  // A second start finds the baseline recorded and changes nothing.
  up(&blank.db).await.unwrap();
  assert_eq!(recorded(&blank.db).await, [BASELINE]);
  assert_eq!(shape(&blank.db).await, before);

  // The service stands on it.
  stand(blank.db.clone(), Arc::new(Rooms::default()), names())
    .await
    .expect("the rules stand");
}

#[tokio::test]
async fn an_install_recording_the_migrations_the_baseline_took_in_is_taken_as_the_baseline() {
  let migrated = Blank::new().await;

  up(&migrated.db).await.unwrap();

  let before = shape(&migrated.db).await;

  for ran in [&FOLDED[..], &FOLDED[..1]] {
    let blank = Blank::new().await;
    let versions: Vec<&str> = std::iter::once(BASELINE).chain(ran.iter().copied()).collect();

    installed_with(&blank, &versions).await;
    up(&blank.db).await.unwrap();

    assert_eq!(recorded(&blank.db).await, [BASELINE], "{ran:?}");
    assert_eq!(
      texts(&blank.db, &format!(r#"SELECT "applied_at"::text FROM "{MIGRATIONS_TABLE}""#)).await,
      ["1"],
      "{ran:?}"
    );
    assert_eq!(shape(&blank.db).await, before, "{ran:?}");
    kept_its_own_and_lost_the_unmade(&blank.db).await;
  }
}

#[tokio::test]
async fn an_install_short_of_the_last_release_before_the_baseline_is_refused() {
  let blank = Blank::new().await;

  installed(&blank, 3).await;

  let refused = up(&blank.db).await.unwrap_err().to_string();

  assert!(refused.contains(BEFORE[2]), "{refused}");
  assert_eq!(recorded(&blank.db).await.len(), 3);
  assert_eq!(count(&blank.db, r#"SELECT COUNT(*) FROM "grant_words""#).await, "1");
}

#[tokio::test]
async fn the_baseline_taken_down_leaves_the_database_blank() {
  let migrated = Blank::new().await;
  let blank = Blank::new().await;

  up(&migrated.db).await.unwrap();
  Migrator::down(&migrated.db, None).await.unwrap();
  record_table(&blank.db).await;

  assert_eq!(shape(&migrated.db).await, shape(&blank.db).await);
  assert!(recorded(&migrated.db).await.is_empty());
  assert_eq!(
    texts(&migrated.db, "SELECT COUNT(*)::text FROM pg_extension WHERE extname = 'uuid-ossp'").await,
    ["0"]
  );
}
